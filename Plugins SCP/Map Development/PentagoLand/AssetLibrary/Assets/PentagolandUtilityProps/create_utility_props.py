def unwrap_mesh(mesh, world_scale=4.0):
    uv_layer = mesh.uv_layers.active or mesh.uv_layers.new(name="UVMap")
    for polygon in mesh.polygons:
        normal = polygon.normal
        dominant_axis = max(range(3), key=lambda axis: abs(normal[axis]))
        uv_axes = ((1, 2), (0, 2), (0, 1))[dominant_axis]
        for loop_index in polygon.loop_indices:
            vertex = mesh.vertices[mesh.loops[loop_index].vertex_index].co
            uv_layer.data[loop_index].uv = (
                vertex[uv_axes[0]] * world_scale,
                vertex[uv_axes[1]] * world_scale,
            )


def finish(obj, name, mat, asset_id):
    obj.name = name
    obj.data.name = name + "Mesh"
    unwrap_mesh(obj.data)
    obj.data.materials.append(mat)
    obj["asset_id"] = asset_id
    return obj


def box(name, location, dimensions, mat, asset_id, bevel=0.02):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=location)
    obj = bpy.context.object
    obj.dimensions = dimensions
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if bevel:
        modifier = obj.modifiers.new("Manufactured edge", "BEVEL")
        modifier.width = bevel
        modifier.segments = 3
        bpy.context.view_layer.objects.active = obj
        bpy.ops.object.modifier_apply(modifier=modifier.name)
        normal_modifier = obj.modifiers.new("Weighted corner normals", "WEIGHTED_NORMAL")
        bpy.ops.object.modifier_apply(modifier=normal_modifier.name)
    return finish(obj, name, mat, asset_id)


def cylinder(name, location, radius, depth, mat, asset_id, rotation=(0.0, 0.0, 0.0), vertices=20):
    bpy.ops.mesh.primitive_cylinder_add(
        vertices=vertices,
        radius=radius,
        depth=depth,
        location=location,
        rotation=rotation,
    )
    obj = bpy.context.object
    modifier = obj.modifiers.new("Machined edge", "BEVEL")
    modifier.width = min(radius * 0.08, depth * 0.15)
    modifier.segments = 3
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.modifier_apply(modifier=modifier.name)
    for polygon in obj.data.polygons:
        polygon.use_smooth = len(polygon.vertices) <= 4
    return finish(obj, name, mat, asset_id)


